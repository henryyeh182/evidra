import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const sdkPath = new URL("../apps/local-engine/src/todayBriefAppSdk.js", import.meta.url);
const bundled = await build({
  stdin: {
    contents: 'import { App } from "@modelcontextprotocol/ext-apps"; export { App };',
    resolveDir: process.cwd(),
    sourcefile: "todayBriefApp.sdk.js"
  },
  bundle: true,
  format: "iife",
  globalName: "PaceveraSdk",
  platform: "browser",
  minify: true,
  write: false
});

const sdk = `${bundled.outputFiles[0].text}\nconst App = PaceveraSdk.App;`;
await writeFile(sdkPath, `// Generated by scripts/build-today-brief-app.js.\nexport const TODAY_BRIEF_APP_SDK = ${JSON.stringify(sdk)};\n`);
console.log("built embedded Today's Brief MCP Apps SDK");
