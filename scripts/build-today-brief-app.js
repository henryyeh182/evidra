import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

const sourcePath = new URL("../apps/local-engine/src/todayBriefApp.js", import.meta.url);
const sdkPath = new URL("../apps/local-engine/src/todayBriefAppSdk.js", import.meta.url);
const source = await readFile(sourcePath, "utf8");
const importLine = 'import { App } from "https://esm.sh/@modelcontextprotocol/ext-apps@1.7.5";';
const placeholder = "${TODAY_BRIEF_APP_SDK}";
const scriptStart = source.indexOf('<script type="module">');
const scriptEnd = source.indexOf("</script>", scriptStart);
if (scriptStart < 0 || scriptEnd < 0) throw new Error("Today's Brief script block is missing");

let appSource = source.slice(scriptStart + '<script type="module">'.length, scriptEnd).trim();
// The browser script lives inside an outer JavaScript template literal, so
// apostrophes in its single-quoted HTML strings are escaped one level too far
// in the source file. Remove that outer level before asking esbuild to parse
// the standalone browser module.
appSource = appSource.replace(/\\\\'/g, "\\'");
if (appSource.includes(importLine)) {
  appSource = appSource.replace(importLine, 'import { App } from "@modelcontextprotocol/ext-apps";');
} else if (appSource.includes(placeholder)) {
  const generated = await readFile(sdkPath, "utf8");
  const match = generated.match(/export const TODAY_BRIEF_APP_SDK = (.*);/s);
  if (!match) throw new Error("Generated Today's Brief SDK is missing");
  const bundledSdk = JSON.parse(match[1]);
  appSource = appSource.replace(placeholder, bundledSdk || 'import { App } from "@modelcontextprotocol/ext-apps";');
}

if (appSource.includes("https://esm.sh/@modelcontextprotocol/ext-apps")) {
  throw new Error("Today's Brief still depends on the CDN SDK");
}
if (appSource.includes('from "@modelcontextprotocol/ext-apps"')) {
  const bundled = await build({
    stdin: { contents: appSource, resolveDir: process.cwd(), sourcefile: "todayBriefApp.mcp-app.js" },
    bundle: true,
    format: "iife",
    platform: "browser",
    minify: true,
    write: false
  });
  await writeFile(sdkPath, `// Generated by scripts/build-today-brief-app.js.\nexport const TODAY_BRIEF_APP_SDK = ${JSON.stringify(bundled.outputFiles[0].text)};\n`);
}

console.log("built embedded Today's Brief MCP Apps SDK");
